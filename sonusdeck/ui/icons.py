_SVG = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">{body}</svg>'
_renderers: dict[tuple[str, str], QSvgRenderer] = {}


def _renderer(paths: tuple[str, ...], color: str) -> QSvgRenderer:
    key = ("|".join(paths), color)
    cached = _renderers.get(key)
    if cached is None:
        body = "".join(f'<path fill="{color}" d="{d}"/>' for d in paths)
        cached = QSvgRenderer(_SVG.format(body=body).encode("utf-8"))
        _renderers[key] = cached
    return cached


def draw_paths(painter: QPainter, paths: list[str], rect: QRectF, color: str) -> None:
    _renderer(tuple(paths), color).render(painter, rect)


def draw_channel(painter: QPainter, key: str, rect: QRectF, color: str) -> None:
    draw_paths(painter, CHANNEL_ICONS.get(key, CHANNEL_ICONS["master"]), rect, color)


def draw_speaker(painter: QPainter, rect: QRectF, color: str, muted: bool) -> None:
    paths = [SPEAKER_BODY, SPEAKER_X] if muted else [
        SPEAKER_BODY, SPEAKER_WAVE_INNER, SPEAKER_WAVE_OUTER
    ]
    draw_paths(painter, paths, rect, color)
